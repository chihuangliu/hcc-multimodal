def _expit(u: np.ndarray) -> np.ndarray:
    return 1.0 / (1.0 + np.exp(-u))


# ---------------------------------------------------------------------------
# Per-member Laplace posteriors
# ---------------------------------------------------------------------------
@dataclass
class MemberPosterior:
    """Gaussian posterior over one member's parameters, plus what it took to get there."""

    name: str
    kind: str  # "logistic" | "platt" | "deterministic"
    idx: np.ndarray  # active columns of the member's transformed design
    phi_hat: np.ndarray  # [w_A, b] (logistic) or [a, c] (platt)
    sigma: np.ndarray  # posterior covariance
    a_squash: float  # ensemble-logit scale factor (1.0 for logistic)
    diag: dict = field(default_factory=dict)

    @property
    def chol(self) -> np.ndarray:
        return np.linalg.cholesky(self.sigma)


def _neg_log_post(phi: np.ndarray, phi_design: np.ndarray, y: np.ndarray, lam: float) -> float:
    """Negative log posterior of the Gaussian-prior logistic model (for the evidence)."""
    u = phi_design @ phi
    nll = float(np.sum(np.logaddexp(0.0, u) - y * u))
    return nll + 0.5 * lam * float(phi @ phi)


def _log_evidence(phi: np.ndarray, phi_design: np.ndarray, y: np.ndarray, lam: float) -> float:
    """Laplace approximation to ``log p(D)``: ``-L(phi) + d/2 log 2pi - 1/2 logdet H``.

    Returns ``-inf`` for a non-positive-definite ``H`` (which happens at the small-lambda end of
    the grid whenever the design is rank-deficient, e.g. the full-support diagnostic where
    ``d > n``), so those candidates simply lose the argmax.
    """
    p = _expit(phi_design @ phi)
    s = p * (1.0 - p)
    h = phi_design.T @ (s[:, None] * phi_design) + lam * np.eye(phi.size)
    eig = np.linalg.eigvalsh(h)
    if eig.min() <= 0:
        return -np.inf
    logdet = float(np.sum(np.log(eig)))
    return -_neg_log_post(phi, phi_design, y, lam) + 0.5 * phi.size * np.log(2 * np.pi) - 0.5 * logdet


def _logistic_posterior(
    pipe,
    x_train: pd.DataFrame,
    y_train: np.ndarray,
    name: str,
    *,
    full_support: bool,
    lam_override: float | None,
    intercept_prior: str,
    cond_max: float,
    lambda_grid: np.ndarray,
) -> MemberPosterior:
    """Post-hoc Laplace posterior for one fitted logistic member. ``pipe`` is never refit."""
    model = pipe.named_steps["model"]
    zt = np.asarray(pipe[:-1].transform(x_train), dtype=float)
    w = model.coef_.ravel()
    idx = np.arange(w.size) if full_support else np.flatnonzero(w)

    phi_hat = np.append(w[idx], model.intercept_[0])
    phi_design = np.column_stack([zt[:, idx], np.ones(len(zt))])

    # Prior precision: the member's own L2 part. l1_ratio == 1 (pure LASSO) supplies none.
    l1_ratio = getattr(model, "l1_ratio", None)
    lam_natural = 0.0 if l1_ratio is None else (1.0 - float(l1_ratio)) / float(model.C)

    p_tr = pipe.predict_proba(x_train)[:, 1]
    s = p_tr * (1.0 - p_tr)
    h_data = phi_design.T @ (s[:, None] * phi_design)

    def _assemble(lam: float) -> np.ndarray:
        prior = np.full(phi_hat.size, lam)
        if intercept_prior == "zero":
            prior[-1] = 0.0
        return h_data + np.diag(prior)

    branch = "natural"
    lam = lam_natural if lam_override is None else float(lam_override)
    if lam_override is not None:
        branch = "fixed"
    elif lam_natural == 0.0:
        # Pure L1: use the data alone if the active-set Hessian can carry it.
        ev = np.linalg.eigvalsh(_assemble(0.0))
        cond = ev.max() / max(ev.min(), 1e-300)
        if ev.min() <= 0 or cond > cond_max:
            scores = [_log_evidence(phi_hat, phi_design, y_train, g) for g in lambda_grid]
            lam = float(lambda_grid[int(np.argmax(scores))])
            branch = "evidence"
        else:
            branch = "data-only"

    h = _assemble(lam)
    eig = np.linalg.eigvalsh(h)
    sigma = np.linalg.inv(h)

    # Residual gradient of the *smooth* part at the deployed weights. Non-zero by KKT for an
    # L1 solution: the reported size of the Taylor expansion's un-cancelled linear term.
    grad = phi_design.T @ (p_tr - y_train) + np.append(lam * phi_hat[:-1], 0.0)

    return MemberPosterior(
        name=name,
        kind="logistic",
        idx=idx,
        phi_hat=phi_hat,
        sigma=sigma,
        a_squash=1.0,
        diag={
            "n_selected": int(w.size),
            "n_active": int(np.count_nonzero(w)),
            "n_params": int(phi_hat.size),
            "l1_ratio": None if l1_ratio is None else float(l1_ratio),
            "C": float(model.C),
            "lambda": float(lam),
            "lambda_natural": float(lam_natural),
            "lambda_branch": branch,
            "cond_H": float(eig.max() / max(eig.min(), 1e-300)),
            "eig_min": float(eig.min()),
            "residual_grad_norm": float(np.linalg.norm(grad)),
            "full_support": bool(full_support),
        },
    )


def _platt_posterior(pipe, x_train: pd.DataFrame, y_train: np.ndarray, name: str) -> MemberPosterior:
    """Laplace posterior over the SVM member's two Platt parameters ``(a, c)``.

    The deployed score is ``sigmoid(a f(z) + c)`` with ``(a, c) = (-probA_, -probB_)``.
    libsvm fits those on *internal CV folds*, so the deployed pair is not exactly the mode of
    the in-sample Platt likelihood -- the residual gradient and an in-sample refit are recorded
    for comparison but never substituted into the model.
    """
    model = pipe.named_steps["model"]
    zt = np.asarray(pipe[:-1].transform(x_train), dtype=float)
    f = model.decision_function(zt)

    phi_hat = np.array([-float(model.probA_[0]), -float(model.probB_[0])])
    psi = np.column_stack([f, np.ones(len(f))])
    q = _expit(psi @ phi_hat)
    h = psi.T @ ((q * (1.0 - q))[:, None] * psi)
    eig = np.linalg.eigvalsh(h)
    sigma = np.linalg.inv(h)
    grad = psi.T @ (q - y_train)

    # In-sample refit, for the diagnostic only.
    refit = phi_hat.copy()
    for _ in range(100):
        qq = _expit(psi @ refit)
        g = psi.T @ (qq - y_train)
        hh = psi.T @ ((qq * (1.0 - qq))[:, None] * psi) + 1e-9 * np.eye(2)
        step = np.linalg.solve(hh, g)
        refit -= step
        if np.linalg.norm(step) < 1e-10:
            break

    return MemberPosterior(
        name=name,
        kind="platt",
        idx=np.array([], dtype=int),
        phi_hat=phi_hat,
        sigma=sigma,
        a_squash=phi_hat[0],
        diag={
            "platt_a": float(phi_hat[0]),
            "platt_c": float(phi_hat[1]),
            "platt_a_insample_refit": float(refit[0]),
            "platt_c_insample_refit": float(refit[1]),
            "cond_H": float(eig.max() / max(eig.min(), 1e-300)),
            "residual_grad_norm": float(np.linalg.norm(grad)),
            "margin_std": float(f.std()),
        },
    )


def _design_at(post: MemberPosterior, pipe, x: pd.DataFrame) -> np.ndarray:
    """The member's design rows for new patients: ``[Zt[:, A], 1]`` or ``[f(z), 1]``."""
    zt = np.asarray(pipe[:-1].transform(x), dtype=float)
    if post.kind == "platt":
        return np.column_stack([pipe.named_steps["model"].decision_function(zt), np.ones(len(zt))])
    return np.column_stack([zt[:, post.idx], np.ones(len(zt))])


def latent_moments(post: MemberPosterior, pipe, x: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]:
    """``(mu, var)`` of the member's contribution on the *ensemble logit* scale.

    For a logistic member ``a = 1`` so this is the raw latent; for the Platt member the squash
    is already inside ``(a, c)``, so the variance needs no extra scaling.
    """
    phi = _design_at(post, pipe, x)
    mu = phi @ post.phi_hat
    var = np.einsum("ij,jk,ik->i", phi, post.sigma, phi)
    return mu, var


