"""Post-hoc Laplace model uncertainty for the frozen top-3 downstream ensemble.

The deployed head (``model_ensemble_members.csv``) is a mean-probability ensemble of a
LASSO logistic, an elastic-net logistic and a Platt-calibrated linear SVM, fitted on the
resection cohort. This module adds an *epistemic uncertainty overlay* without touching the
deployed predictor: each member's MAP weights are taken from the deployed fit unchanged and
only a Hessian is added, so ``p_hat`` here is bit-for-bit the ensemble's own
``predict_proba`` (asserted at run time).

What it produces is a *description* of the deployed model's parameter uncertainty: the size of
each member's posterior, the per-patient magnitude of the resulting predictive spread, and where
each cohort sits in the directions the head actually reads. ``u_epi_3`` -- the posterior of the
whole three-member ensemble -- is the primary quantity.

Two label-free validation questions are carried alongside, because uncertainty that is never
checked against anything is not worth reporting: whether the uncertainty *ranking* separates the
two external cohorts, and whether rejecting the most uncertain patients raises AUROC on the
retained set (risk--coverage). A plain-confidence baseline is kept for both, since the posterior
has to say something the score does not already say.

Method
------
For a logistic member with fitted weights ``w_hat`` on its own transformed design
``Zt = (imputer -> scaler -> selector)(Z)``:

  * the active set ``A = {j : w_hat_j != 0}``; on ``A`` the L1 term is locally linear, so it
    contributes a gradient offset but no curvature;
  * ``H = Phi^T S Phi + Lambda`` with ``Phi = [Zt[:, A], 1]``, ``S = diag(p_i(1 - p_i))``
    at the deployed probabilities, and ``Sigma = H^-1``;
  * the prior precision is the member's *own* L2 part, ``lambda = (1 - l1_ratio) / C`` --
    0.2 for the elastic-net member, and exactly 0 for the pure-L1 LASSO member, whose
    active-set Hessian is well conditioned on its own (nothing is invented);
  * predictive latent moments at ``z*`` are ``mu = phi*^T phi_hat`` and
    ``s2 = phi*^T Sigma phi*``, the Mahalanobis-type term that grows in directions the
    training data did not constrain.

The SVM member has no likelihood, and is handled two ways for comparison: **deterministic**
(contributes its score, zero variance) and **Platt** (a Laplace posterior over the 2 Platt
parameters, which is a genuine logistic likelihood on the margins -- capturing the member's
*calibration* uncertainty only, not its direction).

Outputs are data only -- a results JSON, a per-patient CSV and two figures. Interpretation is
deliberately not templated here: the write-up is authored from the JSON rather than generated by
string formatting, so the prose can follow what the numbers actually say.

Usage
-----
  python -m hcc_multimodal.eval.laplace_uncertainty \\
    --model-id d7085bf5 \\
    --members-csv results/eval/grid_flat3_bestckpt/d7085bf5/model_ensemble_members.csv \\
    --output results/eval/uncertainty/laplace_d7085bf5.json \\
    --fig-dir reports/0810
"""

