# Per-patient uncertainty statistics
# ---------------------------------------------------------------------------
def build_posteriors(
    ens: HeteroEnsembleGrid,
    specs: list[dict],
    x_train: pd.DataFrame,
    y_train: pd.Series,
    *,
    full_support: bool = False,
    lam_override: float | None = None,
    intercept_prior: str = "same",
    cond_max: float = 1e10,
    lambda_grid: np.ndarray | None = None,
) -> list[MemberPosterior]:
    """One posterior per fitted member, in ``ens.members_`` order."""
    if lambda_grid is None:
        lambda_grid = np.logspace(-4, 4, 33)
    yv = np.asarray(y_train, dtype=float)
    out = []
    for spec, pipe in zip(specs, ens.members_):
        name = spec["model"]
        if isinstance(pipe.named_steps["model"], SVC):
            out.append(_platt_posterior(pipe, x_train, yv, name))
        else:
            out.append(
                _logistic_posterior(
                    pipe,
                    x_train,
                    yv,
                    name,
                    full_support=full_support,
                    lam_override=lam_override,
                    intercept_prior=intercept_prior,
                    cond_max=cond_max,
                    lambda_grid=lambda_grid,
                )
            )
    return out


def uncertainty_frame(
    ens: HeteroEnsembleGrid,
    posteriors: list[MemberPosterior],
    posteriors_full: list[MemberPosterior] | None,
    x: pd.DataFrame,
    *,
    n_draws: int,
    seed: int,
) -> pd.DataFrame:
    """Per-patient point score and uncertainty statistics for one cohort.

    ``p_hat`` is the deployed ensemble probability, untouched. Uncertainty is reported on the
    ensemble's shared logit scale (``u_epi_*``) because probability-scale spread is squashed
    near 0 and 1 -- a confidently-wrong OOD patient would otherwise score as *certain*.
    """
    p_hat = ens.predict_proba(x)[:, 1]

    variances, means, kinds = [], [], []
    for post, pipe in zip(posteriors, ens.members_):
        mu, var = latent_moments(post, pipe, x)
        means.append(mu)
        variances.append(var)
        kinds.append(post.kind)

    var_arr = np.array(variances)
    logistic = np.array([k == "logistic" for k in kinds])

    df = pd.DataFrame(index=x.index)
    df["p_hat"] = p_hat
    # Laplace predictive mean: MacKay probit correction per member, then averaged. Reported
    # *alongside* p_hat as a calibration variant -- it never replaces the deployed prediction.
    df["p_laplace"] = np.mean(
        [_expit(mu / np.sqrt(1.0 + np.pi * var / 8.0)) for mu, var in zip(means, variances)], axis=0
    )
    df["u_epi_2"] = np.sqrt(var_arr[logistic].mean(axis=0))
    df["u_epi_3"] = np.sqrt(var_arr.mean(axis=0))
    df["conf"] = -np.abs(p_hat - 0.5)  # higher = more uncertain, for a uniform sort direction

    if posteriors_full is not None:
        vf = np.array(
            [
                latent_moments(p, pipe, x)[1]
                for p, pipe in zip(posteriors_full, ens.members_)
                if p.kind == "logistic"
            ]
        )
        df["u_epi_2_full"] = np.sqrt(vf.mean(axis=0))

    # MC predictive spread on the probability scale (secondary; the mean is never used).
    rng = np.random.default_rng(seed)
    draws = np.zeros((n_draws, len(x)))
    for post, pipe, mu in zip(posteriors, ens.members_, means):
        # latent_m = phi* . (phi_hat + L eps) = mu + (phi* L) eps
        phi_star = _design_at(post, pipe, x)
        eps = rng.standard_normal((n_draws, post.phi_hat.size))
        draws += _expit(mu[None, :] + eps @ (phi_star @ post.chol).T)
    draws /= len(posteriors)
    df["sd_prob"] = draws.std(axis=0)
    df["z_norm"] = np.linalg.norm(np.asarray(x, dtype=float), axis=1)
    return df


def active_geometry(
    posteriors: list[MemberPosterior],
    ens: HeteroEnsembleGrid,
    cohort_x: dict[str, pd.DataFrame],
) -> list[dict]:
    """Where each cohort sits in the handful of directions the head actually reads.

    This is what interprets the uncertainty numbers. ``s2`` can only grow for a patient who is
    displaced *in the active directions*; a cohort that is far away in the ~121 dimensions the
    sparse head ignores is invisible to it. Standardisation is the resection-fitted scaler, so
    resection is centred at 0 with unit spread by construction and the external rows read
    directly as "sigmas away from the training cohort".
    """
    rows = []
    for post, pipe in zip(posteriors, ens.members_):
        if post.kind != "logistic":
            continue
        for cohort, x in cohort_x.items():
            phi = _design_at(post, pipe, x)[:, :-1]  # drop the intercept column
            mu, var = latent_moments(post, pipe, x)
            rows.append(
                {
                    "member": post.name,
                    "cohort": cohort,
                    "n_active_dims": int(phi.shape[1]),
                    "mean_abs_z": float(np.abs(phi).mean()),
                    "median_norm": float(np.median(np.linalg.norm(phi, axis=1))),
                    "median_abs_mu": float(np.median(np.abs(mu))),
                    "median_s2": float(np.median(var)),
                }
            )
    return rows


# ---------------------------------------------------------------------------
# Baseline OOD detector
# ---------------------------------------------------------------------------
def probit_vs_mc(
    posteriors: list[MemberPosterior],
    ens: HeteroEnsembleGrid,
    x: pd.DataFrame,
    *,
    n_draws: int,
    seed: int,
) -> list[dict]:
    """Verification: the MacKay probit approximation of each member's predictive mean must
    agree with sampling from the same posterior. Disagreement means the covariance and the
    sampler have parted company."""
    rng = np.random.default_rng(seed)
    rows = []
    for post, pipe in zip(posteriors, ens.members_):
        mu, var = latent_moments(post, pipe, x)
        analytic = _expit(mu / np.sqrt(1.0 + np.pi * var / 8.0))
        phi_star = _design_at(post, pipe, x)
        eps = rng.standard_normal((n_draws, post.phi_hat.size))
        mc = _expit(mu[None, :] + eps @ (phi_star @ post.chol).T).mean(axis=0)
        rows.append(
            {
                "member": post.name,
                "max_abs_diff": float(np.max(np.abs(analytic - mc))),
                "mean_abs_diff": float(np.mean(np.abs(analytic - mc))),
            }
        )
    return rows


