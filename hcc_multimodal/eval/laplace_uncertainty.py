def run(args: argparse.Namespace) -> None:
    specs = load_members(args.members_csv)
    posterior_kw = dict(
        lam_override=args.lasso_lambda,
        intercept_prior=args.intercept_prior,
        cond_max=args.cond_max,
        lambda_grid=np.logspace(args.lambda_log_min, args.lambda_log_max, args.lambda_steps),
    )

    # --- Step 0: reproduction gate -----------------------------------------
    x_res, y_res = load_cohort(args.model_id, "resection")
    ens = _fit_ensemble(specs, x_res, y_res)
    cv_auc = resection_cv_auc_ensemble(x_res, y_res, specs)
    gate = {"resection_n": int(len(y_res)), "resection_cv_auc": cv_auc}

    cohorts = {}
    for cohort in args.cohorts:
        xc, yc = load_cohort(args.model_id, cohort)
        cohorts[cohort] = (xc, yc)
        gate[f"{cohort}_n"] = int(len(yc))
        gate[f"{cohort}_auroc"] = float(roc_auc_score(yc, ens.predict_proba(xc)[:, 1]))

    print("=== reproduction gate ===")
    print(f"  resection CV AUROC {cv_auc:.4f}  (expect {args.expect_cv:.4f})")
    for cohort in args.cohorts:
        print(f"  {cohort:9s} n={gate[f'{cohort}_n']:3d}  AUROC {gate[f'{cohort}_auroc']:.4f}")
    if abs(cv_auc - args.expect_cv) > args.gate_tol:
        raise SystemExit(
            f"Reproduction gate FAILED: resection CV {cv_auc:.4f} != {args.expect_cv:.4f} "
            f"(tol {args.gate_tol}). Refusing to continue — everything downstream depends on it."
        )

    # --- Step 1/2: posteriors ----------------------------------------------
    post = build_posteriors(ens, specs, x_res, y_res, **posterior_kw)
    post_full = build_posteriors(ens, specs, x_res, y_res, **{**posterior_kw, "full_support": True})
    members_diag = [{"member": p.name, "kind": p.kind, **p.diag} for p in post]

    print("\n=== member posteriors ===")
    for d in members_diag:
        print(f"  {d['member']:<12s} {d['kind']:<10s} " + "  ".join(f"{k}={v}" for k, v in list(d.items())[2:8]))

    beta_params = [dict(zip(("beta", "bias"), _unwind_beta(p, x_res.shape[1]))) for p in ens.members_]
    b = np.array([p["beta"] for p in beta_params])
    bn = b / np.linalg.norm(b, axis=1, keepdims=True)
    beta_cosine = {"names": [s["model"] for s in specs], "matrix": (bn @ bn.T).tolist()}

    # --- Step 3/4: per-patient statistics -----------------------------------
    frames = []
    inv_dev = 0.0

    df_fit = uncertainty_frame(ens, post, post_full, x_res, n_draws=args.n_draws, seed=args.seed)
    df_fit["maha"] = mahalanobis_to_train(x_res, x_res)
    df_fit["cohort"], df_fit["y"] = "resection_fitted", y_res.values
    frames.append(df_fit)

    df_oof = oof_reference(
        specs, x_res, y_res, n_splits=args.oof_folds, seed=args.seed, n_draws=args.n_draws, posterior_kw=posterior_kw
    )
    df_oof["cohort"], df_oof["y"] = "resection_oof", y_res.values
    frames.append(df_oof)

    for cohort, (xc, yc) in cohorts.items():
        d = uncertainty_frame(ens, post, post_full, xc, n_draws=args.n_draws, seed=args.seed)
        d["maha"] = mahalanobis_to_train(x_res, xc)
        d["cohort"], d["y"] = cohort, yc.values
        inv_dev = max(inv_dev, float(np.max(np.abs(d["p_hat"].to_numpy() - ens.predict_proba(xc)[:, 1]))))
        frames.append(d)

    per_patient = pd.concat(frames).rename_axis("SID").reset_index()

    # Verification: point predictions must be untouched.
    if inv_dev > 1e-12:
        raise SystemExit(f"Invariance check FAILED: p_hat deviates by {inv_dev:.2e} from the deployed ensemble.")
    print(f"\ninvariance check OK (max |dev| = {inv_dev:.2e})")

    med_fit = float(np.median(df_fit[args.primary_rule]))
    med_oof = float(np.median(df_oof[args.primary_rule]))
    print(f"resection {args.primary_rule} median: fitted {med_fit:.4f}  vs out-of-fold {med_oof:.4f}")
    if med_fit >= med_oof:
        print("  WARNING: in-sample uncertainty is not below out-of-fold — check the fold logic.")

    probit_check = probit_vs_mc(post, ens, x_res, n_draws=args.n_draws, seed=args.seed)
    worst = max(r["max_abs_diff"] for r in probit_check)
    print(f"probit vs MC predictive mean: max |diff| = {worst:.2e}" + ("" if worst < 1e-2 else "  <-- CHECK"))

    # --- distributions, separation, flag rates ------------------------------
    dist_rows, sep_rows, flag_rows = [], [], []
    rules = [r for r in RULES if r in per_patient.columns]
    thresholds = {r: float(np.percentile(df_oof[r], 95)) for r in rules}

    for cohort, grp in per_patient.groupby("cohort", sort=False):
        for r in rules:
            v = grp[r].to_numpy()
            dist_rows.append(
                {
                    "cohort": cohort,
                    "statistic": r,
                    "n": len(v),
                    "median": float(np.median(v)),
                    "q25": float(np.percentile(v, 25)),
                    "q75": float(np.percentile(v, 75)),
                }
            )
            flag_rows.append(
                {"cohort": cohort, "statistic": r, "flag_rate": float(np.mean(v > thresholds[r]))}
            )

    sor = per_patient[per_patient["cohort"] == "soramic"]
    lau = per_patient[per_patient["cohort"] == "lusanne"]
    if len(sor) and len(lau):
        for r in rules:
            a, c = sor[r].to_numpy(), lau[r].to_numpy()
            lbl = np.r_[np.zeros(len(a)), np.ones(len(c))]
            u_stat, pval = mannwhitneyu(c, a, alternative="two-sided")
            sep_rows.append(
                {
                    "statistic": r,
                    "sep_auroc_lausanne_vs_soramic": float(roc_auc_score(lbl, np.r_[a, c])),
                    "mannwhitney_p": float(pval),
                    "median_soramic": float(np.median(a)),
                    "median_lausanne": float(np.median(c)),
                }
            )

    # Correlations on the external cohorts only — the resection rows are in-sample and would
    # drag every detector toward its own training distribution.
    ext = per_patient[per_patient["cohort"].isin(list(cohorts))]
    corr_rows = []
    for r in rules:
        row = {"statistic": r}
        for other in [*rules, "z_norm"]:
            row[other] = float(spearmanr(ext[r], ext[other]).statistic)
        corr_rows.append(row)

    # --- Step 5: risk--coverage ---------------------------------------------
    coverages = np.arange(1.0, args.coverage_min - 1e-9, -0.05)
    curves, rc_rows = {}, []
    rc_cohorts = [c for c in COHORT_ORDER if c in set(per_patient["cohort"])]
    rc_targets = {c: per_patient[per_patient["cohort"] == c] for c in rc_cohorts}
    for cohort, grp in rc_targets.items():
        curves[cohort] = {}
        for r in rules:
            rc = risk_coverage(
                grp["y"].to_numpy(), grp["p_hat"].to_numpy(), grp[r].to_numpy(), coverages, args.min_per_class
            )
            curves[cohort][r] = rc
            rc_rows.append(
                {
                    "cohort": cohort,
                    "rule": r,
                    "auroc_full": _at_coverage(rc, 1.0),
                    "auroc_at_0.8": _at_coverage(rc, 0.8),
                    "auroc_at_0.6": _at_coverage(rc, 0.6),
                    "mean_auroc_valid": float(np.nanmean(rc["auroc"])),
                }
            )

    # --- calibration: does the posterior imply the right amount of shrinkage? ---
    cal_rows = []
    for cohort, grp in per_patient.groupby("cohort", sort=False):
        for col, variant in (("p_hat", "MAP"), ("p_laplace", "Laplace")):
            cal_rows.append(
                {"cohort": cohort, "variant": variant, **calibration_fit(grp["y"].to_numpy(), grp[col].to_numpy())}
            )

    # --- active-direction geometry (explains the uncertainty numbers) --------
    geom = active_geometry(post, ens, {"resection": x_res, **{c: xc for c, (xc, _) in cohorts.items()}})

    # --- lambda sensitivity --------------------------------------------------
    sweep_rows = []
    for lam in args.lambda_sweep:
        p_s = build_posteriors(ens, specs, x_res, y_res, **{**posterior_kw, "lam_override": lam})
        row = {"lambda": lam}
        u_by_cohort = {}
        for cohort, (xc, yc) in cohorts.items():
            v = np.sqrt(
                np.array(
                    [latent_moments(p, pipe, xc)[1] for p, pipe in zip(p_s, ens.members_) if p.kind == "logistic"]
                ).mean(axis=0)
            )
            u_by_cohort[cohort] = v
            row[f"median_u_{cohort}"] = float(np.median(v))
        if "soramic" in u_by_cohort and "lusanne" in u_by_cohort:
            a, c = u_by_cohort["soramic"], u_by_cohort["lusanne"]
            row["sep_auroc"] = float(roc_auc_score(np.r_[np.zeros(len(a)), np.ones(len(c))], np.r_[a, c]))
        sweep_rows.append(row)

    # --- outputs -------------------------------------------------------------
    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    csv_path = out_path.with_name(out_path.stem + "_per_patient.csv")
    per_patient.to_csv(csv_path, index=False)

    fig_dir = Path(args.fig_dir)
    fig_dir.mkdir(parents=True, exist_ok=True)
    fig_dist = fig_dir / f"{args.fig_prefix}_by_cohort"
    fig_cal = fig_dir / f"{args.fig_prefix}_calibration"
    fig_rc = fig_dir / f"{args.fig_prefix}_risk_coverage"
    fig_uncertainty_by_cohort(per_patient, fig_dist, rule=args.primary_rule, titles=not args.no_fig_title)
    fig_calibration(per_patient, fig_cal, n_bins=args.calibration_bins, titles=not args.no_fig_title)
    fig_risk_coverage(curves, fig_rc, rule=args.primary_rule, titles=not args.no_fig_title)

    payload = {
        "git_commit": git_commit(),
        "timestamp": datetime.now().isoformat(timespec="seconds"),
        "args": {k: (str(v) if isinstance(v, Path) else v) for k, v in vars(args).items()},
        "gate": gate,
        "invariance_max_abs_dev": inv_dev,
        "probit_vs_mc": probit_check,
        "primary_rule": args.primary_rule,
        "resection_primary_median": {"fitted": med_fit, "out_of_fold": med_oof},
        "members": members_diag,
        "beta_cosine": beta_cosine,
        "calibration": cal_rows,
        "active_geometry": geom,
        "p_hat_spread": [
            {
                "cohort": c,
                "median": float(np.median(g["p_hat"])),
                "iqr": float(np.percentile(g["p_hat"], 75) - np.percentile(g["p_hat"], 25)),
                "std": float(g["p_hat"].std()),
            }
            for c, g in per_patient.groupby("cohort", sort=False)
        ],
        "oof_thresholds_p95": thresholds,
        "distributions": dist_rows,
        "separation": sep_rows,
        "flag_rates": flag_rows,
        "correlations": corr_rows,
        "risk_coverage_summary": rc_rows,
        "risk_coverage_curves": {c: {r: rc.to_dict("records") for r, rc in v.items()} for c, v in curves.items()},
        "lambda_sweep": sweep_rows,
        "per_patient_csv": str(csv_path),
        "figures": {
            "by_cohort": str(fig_dist) + ".png",
            "calibration": str(fig_cal) + ".png",
            "risk_coverage": str(fig_rc) + ".png",
        },
    }
    out_path.write_text(json.dumps(payload, indent=2))
    print(f"\nResults → {out_path}")
    print(f"Per-patient → {csv_path}")
    print(f"Figures → {fig_dist}, {fig_cal}, {fig_rc}  (.png/.svg)")

    if sep_rows:
        print("\n=== Soramic vs Lausanne separation (label-free) ===")
        print(pd.DataFrame(sep_rows).to_string(index=False, float_format="%.4f"))
    print("\n=== calibration ===")
    print(pd.DataFrame(cal_rows)[["cohort","variant","base_rate","mean_pred","slope","slope_lo","slope_hi","intercept","brier"]].to_string(index=False, float_format="%.3f"))
    print("\n=== risk-coverage summary ===")
    print(pd.DataFrame(rc_rows).to_string(index=False, float_format="%.4f"))


