# Calibration
# ---------------------------------------------------------------------------
def calibration_fit(y: np.ndarray, p: np.ndarray) -> dict:
    """Cox calibration: an unpenalised logistic regression of ``y`` on ``logit(p)``.

    Slope 1 / intercept 0 is perfect calibration; slope < 1 means the predictions are too
    extreme (the classic overfitting signature), slope > 1 that they are not extreme enough.

    Preferred over binned ECE at n~60: it uses every patient and has no binning degrees of
    freedom, which is the clinical-prediction-model standard (TRIPOD / Steyerberg). Wald
    standard errors come from the same 2x2 logistic Hessian used for the Platt posterior --
    they are *essential* here, because at this sample size the slope is barely identified.
    """
    y = np.asarray(y, dtype=float)
    lp = np.log(np.clip(p, 1e-6, 1 - 1e-6) / (1 - np.clip(p, 1e-6, 1 - 1e-6)))
    design = np.column_stack([lp, np.ones(len(lp))])

    beta = np.zeros(2)
    for _ in range(200):
        q = _expit(design @ beta)
        grad = design.T @ (q - y)
        h = design.T @ ((q * (1.0 - q))[:, None] * design) + 1e-10 * np.eye(2)
        step = np.linalg.solve(h, grad)
        beta -= step
        if np.linalg.norm(step) < 1e-12:
            break

    q = _expit(design @ beta)
    se = np.sqrt(np.diag(np.linalg.inv(design.T @ ((q * (1.0 - q))[:, None] * design))))
    return {
        "slope": float(beta[0]),
        "slope_se": float(se[0]),
        "slope_lo": float(beta[0] - 1.96 * se[0]),
        "slope_hi": float(beta[0] + 1.96 * se[0]),
        "intercept": float(beta[1]),
        "intercept_se": float(se[1]),
        "mean_pred": float(np.mean(p)),
        "base_rate": float(np.mean(y)),
        "brier": float(np.mean((p - y) ** 2)),
    }


def reliability_bins(y: np.ndarray, p: np.ndarray, n_bins: int) -> pd.DataFrame:
    """Equal-count (quantile) bins -- more stable than equal-width at this sample size."""
    order = np.argsort(p)
    rows = []
    for chunk in np.array_split(order, n_bins):
        if len(chunk) == 0:
            continue
        rows.append(
            {
                "n": len(chunk),
                "mean_pred": float(np.mean(p[chunk])),
                "observed": float(np.mean(np.asarray(y, dtype=float)[chunk])),
            }
        )
    return pd.DataFrame(rows)


def mahalanobis_to_train(x_train: pd.DataFrame, x: pd.DataFrame) -> np.ndarray:
    """Mahalanobis distance to the training embedding distribution (Ledoit--Wolf shrinkage,
    required at n=54 in 128 dimensions)."""
    lw = LedoitWolf().fit(np.asarray(x_train, dtype=float))
    return np.sqrt(np.maximum(lw.mahalanobis(np.asarray(x, dtype=float)), 0.0))


# ---------------------------------------------------------------------------
# Risk--coverage
# ---------------------------------------------------------------------------
def risk_coverage(
    y: np.ndarray,
    p_hat: np.ndarray,
    uncertainty: np.ndarray,
    coverages: np.ndarray,
    min_per_class: int = 5,
) -> pd.DataFrame:
    """AUROC of the unchanged ``p_hat`` on the least-uncertain fraction of patients.

    ``NaN`` where a retained subset falls below ``min_per_class`` of either class; the retained
    class counts are emitted alongside so low-coverage instability stays visible.
    """
    order = np.argsort(uncertainty, kind="stable")
    rows = []
    for cov in coverages:
        keep = order[: max(1, int(round(cov * len(order))))]
        yk, pk = y[keep], p_hat[keep]
        n_pos, n_neg = int(yk.sum()), int((1 - yk).sum())
        ok = n_pos >= min_per_class and n_neg >= min_per_class
        rows.append(
            {
                "coverage": float(cov),
                "n": len(keep),
                "n_pos": n_pos,
                "n_neg": n_neg,
                "auroc": float(roc_auc_score(yk, pk)) if ok else np.nan,
            }
        )
    return pd.DataFrame(rows)


def _at_coverage(rc: pd.DataFrame, cov: float) -> float:
    row = rc.iloc[(rc["coverage"] - cov).abs().argmin()]
    return float(row["auroc"])


