def load_cohort(model_id: str, cohort: str) -> tuple[pd.DataFrame, pd.Series]:
    x = load_embeddings(model_id, cohort)
    y = load_survival_outcomes(cohort)["rfs_2year"].dropna().astype(int)
    common = x.index.intersection(y.index).sort_values()
    return x.loc[common], y.loc[common]


def _fit_ensemble(specs: list[dict], x: pd.DataFrame, y: pd.Series) -> HeteroEnsembleGrid:
    ens = HeteroEnsembleGrid([build_member(s["model"], s["fs"], s["params"], s["select_k"]) for s in specs])
    ens.fit(x, y)
    return ens


def oof_reference(
    specs: list[dict],
    x: pd.DataFrame,
    y: pd.Series,
    *,
    n_splits: int,
    seed: int,
    n_draws: int,
    posterior_kw: dict,
) -> pd.DataFrame:
    """Out-of-fold resection uncertainty: per fold, refit the frozen members on the training
    part and build the Hessian from the training part only.

    The in-sample version is biased low by construction (its Hessian is built from the very
    rows being scored), so thresholds are derived from this instead.
    """
    skf = StratifiedKFold(n_splits=n_splits, shuffle=True, random_state=seed)
    parts = []
    for tr, va in skf.split(x, y):
        x_tr, y_tr = x.iloc[tr], y.iloc[tr]
        x_va = x.iloc[va]
        ens = _fit_ensemble(specs, x_tr, y_tr)
        post = build_posteriors(ens, specs, x_tr, y_tr, **posterior_kw)
        post_full = build_posteriors(ens, specs, x_tr, y_tr, **{**posterior_kw, "full_support": True})
        part = uncertainty_frame(ens, post, post_full, x_va, n_draws=n_draws, seed=seed)
        part["maha"] = mahalanobis_to_train(x_tr, x_va)
        parts.append(part)
    return pd.concat(parts).loc[x.index]


